// The anchors MkDocs gives these headings.
func TestSlugMatchesMkDocs(t *testing.T) {
	for heading, want := range map[string]string{
		"0. Prepare":                               "0-prepare",
		"1.2 The stack's configuration":            "12-the-stacks-configuration",
		"2.4 example.com's apex and email records": "24-examplecoms-apex-and-email-records",
		"4. web-app Moves to Prod":                 "4-web-app-moves-to-prod",
		"6.2 Gate: protections for users' data":    "62-gate-protections-for-users-data",
		"How to Use It":                            "how-to-use-it",
	} {
		if got := Slug(heading); got != want {
			t.Errorf("Slug(%q) = %q, want %q", heading, got, want)
		}
	}
}

func resolver(key string) (string, error) {
	if key == "plan:hosting" {
		return "../plan.md#5-hosting-prod", nil
	}
	return "", fmt.Errorf("unknown key %s", key)
}

func TestMarkdown(t *testing.T) {
	rb := sample()
	rb.Usage = "Run [[step:1.1|the last step]] last."
	rb.Later = []Later{{What: "Staging", Needs: "See [[plan:hosting|the plan]]."}}
	rb.Phases[1].Steps[0].Actions = append(rb.Phases[1].Steps[0].Actions,
		Action{Owner: OwnerOperator, Text: "Bring it up.", Command: "pulumi up"})
	out, err := rb.Markdown(RenderOptions{Resolve: resolver, VerifyCommand: "bin/ops verify {step}", Generator: "ops runbook doc"})
	if err != nil {
		t.Fatal(err)
	}
	page := string(out)
	for _, want := range []string{
		"<!-- Generated by ops runbook doc",
		"# Launch\n\nLaunch it.\n",
		"## How to Use It\n\nRun [the last step](#11-up) last.\n",
		"| [0. Prepare](#0-prepare) | 2 | access |",
		"### 0.1 Sign in\n\n**Owner:** operator.\n",
		"**Checks** (`bin/ops verify 0.1`):\n\n- the zone is on Cloudflare\n",
		"Build it.\n\n```bash\nmake build\n```\n",
		"**Owner:** both. **After:** [0.1](#01-sign-in), [0.2](#02-build).",
		"1. Read the steps. See [the plan](../plan.md#5-hosting-prod).",
		"2. **Operator:** Bring it up.\n\n    ```bash\n    pulumi up\n    ```\n",
		"**Creates:** `hosting/prod/ssh-key`.",
		"**Done when** it is up",
		"| Staging | See [the plan](../plan.md#5-hosting-prod). |",
	} {
		if !strings.Contains(page, want) {
			t.Errorf("page lacks %q:\n%s", want, page)
		}
	}
	if strings.HasSuffix(page, "\n\n") || !strings.HasSuffix(page, "\n") {
		t.Error("the page must end in exactly one newline")
	}
}

func TestMarkdownReportsBrokenReferences(t *testing.T) {
	rb := sample()
	rb.Summary = "See [[step:9.9]] and [[plan:nowhere|there]] and [[plan:hosting]]."
	_, err := rb.Markdown(RenderOptions{Resolve: resolver})
	if err == nil {
		t.Fatal("Markdown passed")
	}
	for _, want := range []string{"step 9.9", "unknown key plan:nowhere", "\"plan:hosting\" needs text"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("missing %q in %v", want, err)
		}
	}
	if _, err := sample().Markdown(RenderOptions{}); err == nil || !strings.Contains(err.Error(), "no resolver") {
		t.Errorf("without a resolver: %v", err)
	}
}

func TestBrokenLinks(t *testing.T) {
	dir := t.TempDir()
	other := "# Other\n\n## 5. hosting · prod\n\n```bash\n# not a heading\n```\n"
	if err := os.WriteFile(filepath.Join(dir, "plan.md"), []byte(other), 0o600); err != nil {
		t.Fatal(err)
	}
	page := "# Page\n\n## The `ops` Command\n\n## `APP_DB_DSN`\n\n" +
		"[ok](plan.md#5-hosting-prod) [ok](#the-ops-command) [ok](#app_db_dsn) [web](https://example.com/x#y)\n" +
		"[bad](plan.md#not-a-heading) [bad](#missing) [bad](gone.md) [bad](plan.md#not-a-heading-either)\n" +
		"```\n[in code](nowhere.md)\n```\n"
	broken := BrokenLinks(filepath.Join(dir, "page.md"), []byte(page))
	if len(broken) != 4 {
		t.Fatalf("broken = %d:\n%s", len(broken), strings.Join(broken, "\n"))
	}
	for i, want := range []string{"#not-a-heading", "#missing", "gone.md", "#not-a-heading-either"} {
		if !strings.Contains(broken[i], want) {
			t.Errorf("broken[%d] = %q, want %q", i, broken[i], want)
		}
	}
}
