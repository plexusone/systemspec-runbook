package runbookspec

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
	"unicode"
)

// Resolver turns a link key into a target relative to the rendered page.
type Resolver func(key string) (href string, err error)

// RenderOptions configure the Markdown page.
type RenderOptions struct {
	// Resolve resolves link keys; a key with no resolver is an error.
	Resolve Resolver
	// VerifyCommand, when set, is shown with each step's checks, with
	// {step} replaced by the step's ID, such as
	// "bin/ops verify {step}".
	VerifyCommand string
	// Generator names what writes the page, for the header comment.
	Generator string
}

// ref matches [[step:1.2]], [[step:1.2|text]] and [[key|text]] in Markdown
// text.
var ref = regexp.MustCompile(`\[\[([^\]|]+)(?:\|([^\]]+))?\]\]`)

// Markdown renders the runbook as a page. Text may link to a step with
// [[step:<id>]] or [[step:<id>|text]], and to a resolved target with
// [[<key>|text]], so no anchor or section number is typed by hand.
func (rb *Runbook) Markdown(opts RenderOptions) ([]byte, error) {
	r := &renderer{rb: rb, opts: opts}
	r.page()
	if err := errors.Join(r.errs...); err != nil {
		return nil, err
	}
	return []byte(r.b.String()), nil
}

type renderer struct {
	rb   *Runbook
	opts RenderOptions
	b    strings.Builder
	errs []error
}

func (r *renderer) p(format string, args ...any) { fmt.Fprintf(&r.b, format, args...) }

// text expands the references in Markdown text.
func (r *renderer) text(s string) string {
	return ref.ReplaceAllStringFunc(s, func(m string) string {
		parts := ref.FindStringSubmatch(m)
		key, label := strings.TrimSpace(parts[1]), strings.TrimSpace(parts[2])
		if id, ok := strings.CutPrefix(key, "step:"); ok {
			s := r.rb.Step(id)
			if s == nil {
				r.errs = append(r.errs, fmt.Errorf("runbook: a reference names step %s, which does not exist", id))
				return m
			}
			if label == "" {
				label = id
			}
			return fmt.Sprintf("[%s](#%s)", label, StepAnchor(s))
		}
		if label == "" {
			r.errs = append(r.errs, fmt.Errorf("runbook: reference %q needs text", key))
			return m
		}
		href, err := r.resolve(key)
		if err != nil {
			r.errs = append(r.errs, err)
			return m
		}
		return fmt.Sprintf("[%s](%s)", label, href)
	})
}

func (r *renderer) resolve(key string) (string, error) {
	if r.opts.Resolve == nil {
		return "", fmt.Errorf("runbook: no resolver for link %q", key)
	}
	href, err := r.opts.Resolve(key)
	if err != nil {
		return "", fmt.Errorf("runbook: link %q: %w", key, err)
	}
	return href, nil
}

func (r *renderer) link(l *Link) string {
	href := l.Href
	if l.Key != "" {
		var err error
		if href, err = r.resolve(l.Key); err != nil {
			r.errs = append(r.errs, err)
		}
	}
	return fmt.Sprintf("[%s](%s)", l.Text, href)
}

func (r *renderer) page() {
	rb := r.rb
	if r.opts.Generator != "" {
		r.p("<!-- Generated by %s from the runbook declared in Go; do not edit. -->\n\n", r.opts.Generator)
	}
	r.p("# %s\n\n%s\n\n", rb.Title, r.text(strings.TrimSpace(rb.Summary)))
	if rb.Usage != "" {
		r.p("## How to Use It\n\n%s\n\n", r.text(strings.TrimSpace(rb.Usage)))
	}

	r.p("## Summary\n\n| Phase | Steps | What it gives you |\n|---|---|---|\n")
	for _, ph := range rb.Phases {
		r.p("| [%s](#%s) | %d | %s |\n", phaseHeading(ph), Slug(phaseHeading(ph)), len(ph.Steps), r.text(ph.Gives))
	}
	r.p("\n")

	for _, ph := range rb.Phases {
		r.p("## %s\n\n", phaseHeading(ph))
		if ph.Summary != "" {
			r.p("%s\n\n", r.text(strings.TrimSpace(ph.Summary)))
		}
		for i := range ph.Steps {
			r.step(&ph.Steps[i])
		}
	}

	if len(rb.Later) > 0 {
		r.p("## Later\n\n| What | Needs |\n|---|---|\n")
		for _, l := range rb.Later {
			r.p("| %s | %s |\n", l.What, r.text(l.Needs))
		}
	}
	// One trailing newline.
	out := strings.TrimRight(r.b.String(), "\n") + "\n"
	r.b.Reset()
	r.b.WriteString(out)
}

func (r *renderer) step(s *Step) {
	r.p("### %s\n\n", stepHeading(s))
	r.p("**Owner:** %s.", ownerText(s.Owner))
	if len(s.DependsOn) > 0 {
		var deps []string
		for _, d := range s.DependsOn {
			deps = append(deps, r.text("[[step:"+d+"]]"))
		}
		r.p(" **After:** %s.", strings.Join(deps, ", "))
	}
	r.p("\n\n")
	if s.Summary != "" {
		r.p("%s\n\n", r.text(strings.TrimSpace(s.Summary)))
	}
	r.actions(s)
	for _, n := range s.Notes {
		r.p("%s\n\n", r.text(strings.TrimSpace(n)))
	}
	if len(s.Credentials) > 0 {
		var ids []string
		for _, c := range s.Credentials {
			ids = append(ids, "`"+c+"`")
		}
		r.p("**Creates:** %s.\n\n", strings.Join(ids, ", "))
	}
	r.p("**Done when** %s\n\n", r.text(strings.TrimSpace(s.Done)))
	if len(s.Checks) > 0 {
		r.p("**Checks**")
		if r.opts.VerifyCommand != "" {
			r.p(" (`%s`)", strings.ReplaceAll(r.opts.VerifyCommand, "{step}", s.ID))
		}
		r.p(":\n\n")
		for _, c := range s.Checks {
			r.p("- %s\n", r.text(c.Description))
		}
		r.p("\n")
	}
}

// actions renders one action as paragraphs, and several as a numbered
// list, each naming its owner when the step has more than one.
func (r *renderer) actions(s *Step) {
	if len(s.Actions) == 1 && s.Actions[0].Owner == "" {
		a := s.Actions[0]
		if a.Text != "" {
			r.p("%s%s\n\n", r.text(strings.TrimSpace(a.Text)), r.linkSuffix(a))
		}
		if a.Command != "" {
			r.p("```bash\n%s\n```\n\n", strings.TrimSpace(a.Command))
		}
		return
	}
	for i, a := range s.Actions {
		prefix := ""
		if a.Owner != "" {
			prefix = "**" + capitalize(ownerText(a.Owner)) + ":** "
		}
		r.p("%d. %s%s%s\n", i+1, prefix, indent(r.text(strings.TrimSpace(a.Text)), "    ", false), r.linkSuffix(a))
		if a.Command != "" {
			r.p("\n    ```bash\n%s\n    ```\n", indent(strings.TrimSpace(a.Command), "    ", true))
		}
		if i < len(s.Actions)-1 && a.Command != "" {
			r.p("\n")
		}
	}
	r.p("\n")
}

func (r *renderer) linkSuffix(a Action) string {
	if a.Link == nil {
		return ""
	}
	return " See " + r.link(a.Link) + "."
}

// indent indents every line after the first, or every line when all is
// true, so text continues inside a list item.
func indent(s, pad string, all bool) string {
	lines := strings.Split(s, "\n")
	for i := range lines {
		if (i > 0 || all) && lines[i] != "" {
			lines[i] = pad + lines[i]
		}
	}
	return strings.Join(lines, "\n")
}

func phaseHeading(p Phase) string { return p.ID + ". " + p.Title }

func stepHeading(s *Step) string { return s.ID + " " + s.Title }

// StepAnchor is the anchor of a step's heading on the rendered page.
func StepAnchor(s *Step) string { return Slug(stepHeading(s)) }

func ownerText(o Owner) string {
	switch o {
	case OwnerOperator:
		return "operator"
	case OwnerAgent:
		return "agent"
	case OwnerBoth:
		return "both"
	}
	return string(o)
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

var (
	slugDrop  = regexp.MustCompile(`[^\w\s-]`)
	slugSpace = regexp.MustCompile(`[-\s]+`)
)

// Slug is the anchor MkDocs' table of contents gives a heading: lower case,
// punctuation dropped, runs of spaces and hyphens joined by one hyphen.
func Slug(heading string) string {
	var b strings.Builder
	for _, r := range heading {
		if r < unicode.MaxASCII {
			b.WriteRune(r)
		}
	}
	s := slugDrop.ReplaceAllString(b.String(), "")
	s = strings.ToLower(strings.TrimSpace(s))
	return slugSpace.ReplaceAllString(s, "-")
}
